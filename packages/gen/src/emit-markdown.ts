import type { EmittedFile } from "./emitted.js";
import { pascalCase } from "./naming.js";
import { type ContractSchema, type JsonSchema, refName } from "./schema.js";

export interface EmitMarkdownOptions {
  /** 文書の見出し（既定 "契約仕様"） */
  title?: string;
  /** HTTP で提供するときの path 接頭辞（`openapi.basePath` と揃える。既定 ""） */
  basePath?: string;
  /** HTTP で提供するときのイベント（Server-Sent Events）の path（既定 "/events"。`false` で HTTP の行を出さない） */
  eventsPath?: string | false;
}

/**
 * contract.schema.json → contract.md
 *
 * 人と AI が読む契約の仕様書。メソッドごとに呼び出し方（JSON-RPC / HTTP / TypeScript / VB.NET）と入出力の項目表、
 * イベント、共有型、エラーコード、型の対応を 1 枚にまとめる。型名は VB の DTO（`<Ns><Method>Request` / `Response`、
 * `<Name>Event`）と TS（`<Ns><Method>Input` / `Output`）の両方を書くので、どちら側のコードからも引ける。
 * 無名の入れ子 object は別の型にせず、`address.line1` / `children[].childId` のように経路で平らに並べる。
 */
export function emitMarkdown(schema: ContractSchema, options: EmitMarkdownOptions = {}): EmittedFile[] {
  return [{ path: "contract.md", content: new MarkdownWriter(schema, options).render() }];
}

type Row = string[];

class MarkdownWriter {
  private readonly out: string[] = [];
  private readonly basePath: string;
  private readonly eventsPath: string | false;

  constructor(
    private readonly schema: ContractSchema,
    private readonly options: EmitMarkdownOptions,
  ) {
    this.basePath = normalizePath(options.basePath ?? "");
    this.eventsPath = options.eventsPath === undefined ? "/events" : options.eventsPath;
  }

  render(): string {
    this.line(
      "<!-- <auto-generated>",
      "     This document was generated by @ishibashi0112/webview2-bridge-gen from contract.schema.json.",
      "     DO NOT EDIT. Changes will be lost when `pnpm gen` runs.",
      "</auto-generated> -->",
      `# ${this.options.title ?? "契約仕様"}`,
      "",
      "zod で書いた契約（`contract.ts`）から生成した仕様書。画面（TypeScript）の型と VB.NET の DTO / Interface は同じ契約から生成されるので、この文書と実装は常に一致する。",
      "",
      "- 呼び出しは JSON-RPC 2.0（WebView2 の postMessage）。`method` は `<namespace>.<name>`、Host → Web の通知は `event.<name>`",
      "- HTTP で提供する場合は `POST /<namespace>/<name>`（body = 入力、200 の body = 出力。JSON-RPC の封筒は付けない）。詳細は `openapi.json`",
      "- 日付は ISO 8601 の文字列で往復する",
      "- 「任意」の項目は省略できる（JSON に含めない）。`null` を許す項目は型に `| null` と書く",
      "",
    );
    this.renderMethodIndex();
    this.renderMethods();
    this.renderEvents();
    this.renderDefs();
    this.renderErrors();
    this.renderTypeMapping();
    return `${this.out
      .join("\n")
      .replace(/\n{3,}/g, "\n\n")
      .trimEnd()}\n`;
  }

  // ---------------------------------------------------------------- sections

  private renderMethodIndex(): void {
    this.line("## メソッド一覧", "");
    const rows: Row[] = [];
    for (const [ns, methods] of Object.entries(this.schema.methods)) {
      for (const [name, m] of Object.entries(methods)) {
        const rpc = `${ns}.${name}`;
        rows.push([
          `[\`${rpc}\`](#${slug(rpc)})`,
          this.typeNameOf(m.input, `${pascalCase(ns)}${pascalCase(name)}Request`),
          this.typeNameOf(m.output, `${pascalCase(ns)}${pascalCase(name)}Response`),
          m.input.description ?? "",
        ]);
      }
    }
    if (rows.length === 0) this.line("（メソッドなし）", "");
    else this.table(["メソッド", "入力", "出力", "説明"], rows);
  }

  private renderMethods(): void {
    for (const [ns, methods] of Object.entries(this.schema.methods)) {
      this.line(`## ${ns}`, "", `VB.NET の実装 Interface は \`I${pascalCase(ns)}Api\`。`, "");
      for (const [name, m] of Object.entries(methods)) {
        const base = `${pascalCase(ns)}${pascalCase(name)}`;
        const request = this.typeNameOf(m.input, `${base}Request`);
        const response = this.typeNameOf(m.output, `${base}Response`);
        this.line(`### ${ns}.${name}`, "");
        if (m.input.description) this.line(m.input.description, "");
        this.table(
          ["経路", "呼び出し方"],
          [
            ["JSON-RPC", `\`"method": "${ns}.${name}"\`、\`params\` = 入力、\`result\` = 出力`],
            ["HTTP", `\`POST ${this.basePath}/${ns}/${name}\``],
            ["TypeScript", `\`client.${ns}.${name}(input)\`。型は \`${base}Input\` / \`${base}Output\``],
            [
              "VB.NET",
              `\`I${pascalCase(ns)}Api.${pascalCase(name)}(req As ${plain(request)}) As Task(Of ${plain(response)})\``,
            ],
          ],
        );
        this.renderObject("入力", m.input, request);
        this.renderObject("出力", m.output, response);
      }
    }
  }

  private renderEvents(): void {
    this.line("## イベント（Host → Web）", "");
    const names = Object.keys(this.schema.events);
    if (names.length === 0) {
      this.line("（イベントなし）", "");
      return;
    }
    this.line(
      "進捗表示などの補助的な通知。取りこぼしうる前提で使い、業務の正しさをイベントに依存させない。VB.NET からは `BridgeEvents` で発行する。",
      "",
    );
    for (const name of names) {
      const e = this.schema.events[name]!;
      const payload = this.typeNameOf(e, `${pascalCase(name)}Event`);
      this.line(`### event.${name}`, "");
      if (e.description) this.line(e.description, "");
      const rows: Row[] = [["JSON-RPC", `通知 \`{ "method": "event.${name}", "params": <ペイロード> }\`（id なし）`]];
      if (this.eventsPath !== false) {
        rows.push([
          "HTTP",
          `\`GET ${this.basePath}${normalizePath(this.eventsPath)}\`（Server-Sent Events）の \`data:\` 行`,
        ]);
      }
      rows.push(
        ["TypeScript", `\`client.events.on("${name}", (payload) => ...)\`。型は \`${pascalCase(name)}Event\``],
        ["VB.NET", `\`BridgeEvents.${pascalCase(name)}(payload As ${plain(payload)})\``],
      );
      this.table(["経路", "発行 / 購読"], rows);
      this.renderObject("ペイロード", e, payload);
    }
  }

  private renderDefs(): void {
    const ids = Object.keys(this.schema.$defs);
    if (ids.length === 0) return;
    this.line(
      "## 共有型（`.meta({ id })`）",
      "",
      "複数の場所から参照される型。名前は TypeScript の型名、VB.NET のクラス名と同じ。",
      "",
    );
    for (const id of ids) {
      const def = this.schema.$defs[id]!;
      this.line(`### ${id}`, "");
      if (def.description) this.line(def.description, "");
      if (isStringEnum(def)) {
        const values = (def.enum ?? []).filter((v): v is string => typeof v === "string");
        this.line(
          `文字列の列挙: ${values.map((v) => `\`"${v}"\``).join(" / ")}`,
          "",
          `VB.NET では \`String\` のまま往復し、\`${id}\` クラスの \`Public Const\` に各値を持つ。`,
          "",
        );
      } else {
        this.fieldTable(def);
      }
    }
  }

  private renderErrors(): void {
    this.line(
      "## エラー",
      "",
      "失敗の応答は JSON-RPC の `error` オブジェクト `{ code, message, data }`。HTTP では同じオブジェクトを body に載せ、右の状態コードを返す。",
      "",
    );
    this.table(
      ["code", "意味", "HTTP", "いつ起きるか"],
      [
        ["-32700", "Parse error", "400", "要求が JSON として読めない"],
        ["-32600", "Invalid Request", "400", "JSON-RPC の封筒の形が不正（`method` が無い等）"],
        ["-32601", "Method not found", "404", "契約に無いメソッド"],
        [
          "-32602",
          "Invalid params",
          "400",
          "入力が契約に合わない。VB.NET 側でデシリアライズに失敗したか、必須・文字数・範囲・列挙の検証に通らなかった（`data` に項目ごとの理由）",
        ],
        ["-32603", "Internal error", "500", "transport 層の失敗（応答待ちのタイムアウト、切断、HTTP の不正な応答）"],
        [
          "-32000",
          "Server error",
          "500",
          "VB.NET 実装の未処理例外。`message` は例外メッセージ、`data` は例外型名。実装が `JsonRpcException(code, message, data)` を投げれば -32000 以下の任意のコードを返せる",
        ],
      ],
    );
    this.line(
      '画面側は送信前に入力を zod で検証し、合わなければ送らずに `BridgeValidationError`（`direction: "input"`）にする。受信した出力とイベントも検証する（`"output"` / `"event"`）。',
      "",
    );
  }

  private renderTypeMapping(): void {
    this.line("## 型の対応", "");
    this.table(
      ["契約（zod）", "JSON Schema", "TypeScript", "VB.NET"],
      [
        ["`z.string()`", "string", "`string`", "`String`"],
        ["`z.number()`", "number", "`number`", "`Double`"],
        ["`z.number().int()`", "integer", "`number`", "`Integer`（`format: int64` なら `Long`）"],
        ["`z.boolean()`", "boolean", "`boolean`", "`Boolean`"],
        ["`z.array(T)`", "array", "`T[]`", "`List(Of T)`"],
        [
          "`z.record(z.string(), T)`",
          "object + additionalProperties",
          "`Record<string, T>`",
          "`Dictionary(Of String, T)`",
        ],
        ["`z.object({...})`", "object", "オブジェクト型", "生成クラス（無名なら `<親><項目>`）"],
        ["`z.enum([...])`", "string + enum", "文字列リテラルの union", "`String`（値の定数を持つクラス）"],
        ["`.optional()`", "`required` に含めない", "`?:`", "省略時は `Nothing`（値型は `Nullable(Of T)`）"],
        ["`.nullable()`", '`type: [T, "null"]`', "`T | null`", "`Nothing` 可（値型は `Nullable(Of T)`）"],
        ["`z.unknown()`", "{}", "`unknown`", "`JToken`"],
        ["`z.string().describe(...)`", "description", "doc コメント", "XML doc コメント"],
      ],
    );
    this.line(
      "",
      "`z.union` / `z.intersection` / `z.date` / `bigint` は契約に使えない（生成時にエラーで止まる）。日付は ISO 8601 文字列。",
      "",
    );
  }

  // ---------------------------------------------------------------- objects

  /** method の入出力・event のペイロード。`$ref` なら共有型への参照だけを書く */
  private renderObject(label: string, s: JsonSchema, typeName: string): void {
    if (s.$ref) {
      this.line(`**${label}** ${typeName}（共有型）`, "");
      return;
    }
    this.line(`**${label}** ${typeName}`, "");
    this.fieldTable(s);
  }

  private fieldTable(s: JsonSchema): void {
    const rows: Row[] = [];
    this.fieldRows(s, "", rows);
    if (rows.length === 0) this.line("（項目なし）", "");
    else this.table(["項目", "型", "必須", "説明"], rows);
  }

  private fieldRows(s: JsonSchema, prefix: string, rows: Row[]): void {
    const required = new Set(s.required ?? []);
    for (const [name, ps] of Object.entries(s.properties ?? {})) {
      const path = `${prefix}${name}`;
      rows.push([`\`${path}\``, this.typeLabel(ps), required.has(name) ? "必須" : "任意", ps.description ?? ""]);
      const nested = anonymousObjectOf(ps);
      if (nested) this.fieldRows(nested.schema, `${path}${nested.suffix}.`, rows);
    }
  }

  // ---------------------------------------------------------------- types

  /** 共有型なら `[Name](#name)`、そうでなければ既定名を `code` で */
  private typeNameOf(s: JsonSchema, fallback: string): string {
    if (s.$ref) {
      const id = refName(s.$ref);
      return `[\`${id}\`](#${slug(id)})`;
    }
    return `\`${fallback}\``;
  }

  private typeLabel(s: JsonSchema): string {
    const { core, nullable } = unwrap(s);
    let label: string;
    if (core.$ref) {
      const id = refName(core.$ref);
      label = `[${id}](#${slug(id)})`;
    } else if (core.enum) {
      label = core.enum
        .filter((v) => v !== null)
        .map((v) => `\`${JSON.stringify(v)}\``)
        .join(" / ");
    } else {
      const type = Array.isArray(core.type) ? core.type[0] : core.type;
      switch (type) {
        case "string":
          label = `string${stringConstraints(core)}`;
          break;
        case "number":
          label = `number${numberConstraints(core)}`;
          break;
        case "integer":
          label = `${core.format === "int64" ? "integer (int64)" : "integer"}${numberConstraints(core)}`;
          break;
        case "boolean":
          label = "boolean";
          break;
        case "array": {
          const items = core.items ?? {};
          const inner = anonymousObjectOf(items) ? "object" : this.typeLabel(items);
          label = `${inner.includes(" ") ? `(${inner})` : inner}[]${arrayConstraints(core)}`;
          break;
        }
        case "object":
          if (core.properties && Object.keys(core.properties).length > 0) label = "object";
          else if (typeof core.additionalProperties === "object")
            label = `Record<string, ${anonymousObjectOf(core.additionalProperties) ? "object" : this.typeLabel(core.additionalProperties)}>`;
          else label = "object";
          break;
        default:
          label = "any";
      }
    }
    return nullable ? `${label} | null` : label;
  }

  // ---------------------------------------------------------------- output

  private line(...lines: string[]): void {
    this.out.push(...lines);
  }

  private table(header: string[], rows: Row[]): void {
    this.out.push(`| ${header.join(" | ")} |`, `|${header.map(() => "---").join("|")}|`);
    for (const r of rows) this.out.push(`| ${r.map(cell).join(" | ")} |`);
    this.out.push("");
  }
}

// ------------------------------------------------------------------ helpers

/** `type: [X, "null"]` / `anyOf: [X, {type:"null"}]` を「null 許容の X」に正規化する */
function unwrap(s: JsonSchema): { core: JsonSchema; nullable: boolean } {
  const union = s.anyOf ?? s.oneOf;
  if (union) {
    const nonNull = union.filter((u) => u.type !== "null");
    if (nonNull.length === 1) {
      const inner = unwrap(nonNull[0]!);
      return { core: inner.core, nullable: inner.nullable || nonNull.length !== union.length };
    }
    return { core: s, nullable: false };
  }
  if (Array.isArray(s.type)) {
    const rest = s.type.filter((t) => t !== "null");
    return { core: { ...s, type: rest.length === 1 ? rest[0]! : rest }, nullable: s.type.includes("null") };
  }
  return { core: s, nullable: false };
}

/** 無名の入れ子 object（直下 / 配列の要素 / record の値）。項目表に経路で平らに並べるために使う */
function anonymousObjectOf(s: JsonSchema): { schema: JsonSchema; suffix: string } | undefined {
  const { core } = unwrap(s);
  if (core.$ref) return undefined;
  const type = Array.isArray(core.type) ? core.type[0] : core.type;
  if (type === "object" && core.properties && Object.keys(core.properties).length > 0) {
    return { schema: core, suffix: "" };
  }
  if (type === "array" && core.items) {
    const item = anonymousObjectOf(core.items);
    if (item && item.suffix === "") return { schema: item.schema, suffix: "[]" };
  }
  if (type === "object" && typeof core.additionalProperties === "object") {
    const value = anonymousObjectOf(core.additionalProperties);
    if (value && value.suffix === "") return { schema: value.schema, suffix: ".*" };
  }
  return undefined;
}

function isStringEnum(s: JsonSchema): boolean {
  return Array.isArray(s.enum) && s.enum.every((v) => typeof v === "string");
}

function stringConstraints(s: JsonSchema): string {
  const parts: string[] = [];
  const min = numberOf(s["minLength"]);
  const max = numberOf(s["maxLength"]);
  if (min !== undefined && max !== undefined) parts.push(`${min}〜${max} 文字`);
  else if (min !== undefined) parts.push(`${min} 文字以上`);
  else if (max !== undefined) parts.push(`${max} 文字以下`);
  if (typeof s.format === "string") parts.push(`形式 ${s.format}`);
  if (typeof s["pattern"] === "string") parts.push(`正規表現 \`${s["pattern"]}\``);
  return parts.length > 0 ? `（${parts.join("、")}）` : "";
}

function numberConstraints(s: JsonSchema): string {
  const parts: string[] = [];
  // zod 4 の .int() は minimum / maximum に ±Number.MAX_SAFE_INTEGER を書く。契約の意図ではないので表示しない
  const bound = (v: unknown): number | undefined => {
    const n = numberOf(v);
    return n === undefined || Math.abs(n) === Number.MAX_SAFE_INTEGER ? undefined : n;
  };
  const min = bound(s["minimum"]);
  const xmin = bound(s["exclusiveMinimum"]);
  const max = bound(s["maximum"]);
  const xmax = bound(s["exclusiveMaximum"]);
  if (min !== undefined) parts.push(`${min} 以上`);
  if (xmin !== undefined) parts.push(`${xmin} より大きい`);
  if (max !== undefined) parts.push(`${max} 以下`);
  if (xmax !== undefined) parts.push(`${xmax} 未満`);
  const mult = numberOf(s["multipleOf"]);
  if (mult !== undefined) parts.push(`${mult} の倍数`);
  return parts.length > 0 ? `（${parts.join("、")}）` : "";
}

function arrayConstraints(s: JsonSchema): string {
  const parts: string[] = [];
  const min = numberOf(s["minItems"]);
  const max = numberOf(s["maxItems"]);
  if (min !== undefined && max !== undefined) parts.push(`${min}〜${max} 件`);
  else if (min !== undefined) parts.push(`${min} 件以上`);
  else if (max !== undefined) parts.push(`${max} 件以下`);
  return parts.length > 0 ? `（${parts.join("、")}）` : "";
}

function numberOf(v: unknown): number | undefined {
  return typeof v === "number" ? v : undefined;
}

/** 表のセル用に `|` と改行を逃がす */
function cell(text: string | undefined): string {
  if (!text) return "";
  return text.replace(/\|/g, "\\|").replace(/\r?\n/g, "<br>");
}

/** `[\`Name\`](#name)` / `\`Name\`` から表示用の素の名前を取り出す */
function plain(typeName: string): string {
  const m = /^\[`([^`]+)`\]/.exec(typeName) ?? /^`([^`]+)`$/.exec(typeName);
  return m ? m[1]! : typeName;
}

/** GitHub 風の見出しアンカー（小文字化、記号を除き、空白を - に） */
function slug(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s-]/gu, "")
    .trim()
    .replace(/\s+/g, "-");
}

/** "" / "/api" / "api/" → "" / "/api" / "/api" */
function normalizePath(p: string): string {
  const trimmed = p.trim().replace(/\/+$/, "");
  if (trimmed === "") return "";
  return trimmed.startsWith("/") ? trimmed : `/${trimmed}`;
}
