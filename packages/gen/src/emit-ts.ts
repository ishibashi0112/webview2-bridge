import { isTsReserved, pascalCase } from "./naming.js";
import { GenerateError, refName, type ContractSchema, type JsonSchema } from "./schema.js";
import type { EmittedFile } from "./emitted.js";

export interface EmitTsOptions {
  /** 契約モジュールの import 指定子（例: "@webview2-bridge/contract"） */
  contractImport: string;
  /** 契約モジュールが export している名前 */
  contractExport?: string;
}

/**
 * contract.schema.json → contract-types.ts
 * 型は zod 契約から `z.input` / `z.output` で引く（JSON Schema から型を再構築しない）。
 * JSON Schema は「どのメソッド・イベント・$defs があるか」と、$defs へ到達する経路の決定に使う。
 */
export function emitTs(schema: ContractSchema, options: EmitTsOptions): EmittedFile[] {
  const exportName = options.contractExport ?? "contract";
  const out: string[] = [];
  out.push("// <auto-generated>");
  out.push("//     This code was generated by @ishibashi0112/webview2-bridge-gen from contract.schema.json.");
  out.push("//     DO NOT EDIT. Changes will be lost when `pnpm gen` runs.");
  out.push("// </auto-generated>");
  out.push('import type { z } from "zod";');
  out.push(`import type { ${exportName} } from ${JSON.stringify(options.contractImport)};`);
  out.push("");
  out.push(`type C = typeof ${exportName};`);
  out.push("");

  const methodEntries: { rpcName: string; input: string; output: string }[] = [];
  const defPaths = new Map<string, string>();

  out.push("// ---- methods");
  for (const [ns, methods] of Object.entries(schema.methods)) {
    for (const [name, m] of Object.entries(methods)) {
      const base = `${pascalCase(ns)}${pascalCase(name)}`;
      const access = `C["methods"][${JSON.stringify(ns)}][${JSON.stringify(name)}]`;
      const inputName = `${base}Input`;
      const outputName = `${base}Output`;
      out.push(`/** \`${ns}.${name}\` の入力 */`);
      out.push(`export type ${inputName} = z.input<${access}["input"]>;`);
      out.push(`/** \`${ns}.${name}\` の出力 */`);
      out.push(`export type ${outputName} = z.output<${access}["output"]>;`);
      methodEntries.push({ rpcName: `${ns}.${name}`, input: inputName, output: outputName });
      collectDefPaths(m.input, inputName, `methods.${ns}.${name}.input`, defPaths, schema.$defs);
      collectDefPaths(m.output, outputName, `methods.${ns}.${name}.output`, defPaths, schema.$defs);
    }
  }
  out.push("");
  out.push("// ---- events");
  const eventEntries: { name: string; type: string }[] = [];
  for (const [name, e] of Object.entries(schema.events)) {
    const typeName = `${pascalCase(name)}Event`;
    out.push(`/** \`event.${name}\` のペイロード */`);
    out.push(`export type ${typeName} = z.output<C["events"][${JSON.stringify(name)}]>;`);
    eventEntries.push({ name, type: typeName });
    collectDefPaths(e, typeName, `events.${name}`, defPaths, schema.$defs);
  }
  out.push("");
  out.push("// ---- named types (.meta({ id }))");
  for (const id of Object.keys(schema.$defs)) {
    const p = defPaths.get(id);
    if (!p) {
      throw new GenerateError(`$defs "${id}" is not referenced from any method or event`, `$defs.${id}`);
    }
    if (isTsReserved(id)) throw new GenerateError(`meta id "${id}" is a reserved word in TypeScript`, `$defs.${id}`);
    out.push(`export type ${id} = ${p};`);
  }
  out.push("");
  out.push("// ---- maps");
  out.push("export interface MethodMap {");
  for (const m of methodEntries) {
    out.push(`  ${JSON.stringify(m.rpcName)}: { input: ${m.input}; output: ${m.output} };`);
  }
  out.push("}");
  out.push("export interface EventMap {");
  for (const e of eventEntries) {
    out.push(`  ${JSON.stringify(e.name)}: ${e.type};`);
  }
  out.push("}");
  out.push("export type MethodName = keyof MethodMap;");
  out.push("export type EventName = keyof EventMap;");
  out.push(`export const methodNames = [${methodEntries.map((m) => JSON.stringify(m.rpcName)).join(", ")}] as const;`);
  out.push(`export const eventNames = [${eventEntries.map((e) => JSON.stringify(e.name)).join(", ")}] as const;`);
  return [{ path: "contract-types.ts", content: out.join("\n") + "\n" }];
}

/**
 * `$ref` に最初に到達した経路を TS の indexed access 型として記録する。
 * 例: PartsSearchOutput["items"][number]
 */
function collectDefPaths(
  s: JsonSchema,
  rootExpr: string,
  path: string,
  acc: Map<string, string>,
  defs: Record<string, JsonSchema>,
): void {
  const visit = (node: JsonSchema, expr: string, viaOptional: boolean, p: string): void => {
    if (node.$ref) {
      const id = refName(node.$ref);
      if (acc.has(id)) return;
      acc.set(id, viaOptional ? `NonNullable<${expr}>` : expr);
      // $defs の中で参照される $defs は、その名前付き型を起点に辿る（例: Address = NonNullable<Customer["address"]>）
      const def = defs[id];
      if (def) visit(def, id, false, `$defs.${id}`);
      return;
    }
    const nullable =
      (Array.isArray(node.type) && node.type.includes("null")) ||
      Boolean((node.anyOf ?? node.oneOf)?.some((u) => u.type === "null"));
    const union = (node.anyOf ?? node.oneOf)?.filter((u) => u.type !== "null");
    if (union && union.length === 1) {
      visit(union[0]!, expr, viaOptional || nullable, p);
      return;
    }
    const required = new Set(node.required ?? []);
    for (const [name, child] of Object.entries(node.properties ?? {})) {
      visit(child, `${expr}[${JSON.stringify(name)}]`, viaOptional || nullable || !required.has(name), `${p}.${name}`);
    }
    if (node.items) visit(node.items, `${expr}[number]`, viaOptional || nullable, `${p}[]`);
    if (typeof node.additionalProperties === "object") {
      visit(node.additionalProperties, `${expr}[string]`, viaOptional || nullable, `${p}.*`);
    }
  };
  visit(s, rootExpr, false, path);
}
