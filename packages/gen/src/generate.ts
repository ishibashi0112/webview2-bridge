export interface GenerateConfig {
  /** zod 契約モジュール（`export const contract = defineContract(...)`） */
  contract: string;
  /** 契約モジュールの export 名（既定 "contract"） */
  contractExport?: string;
  /** contract.schema.json の出力先 */
  schemaOut: string;
  ts?: { outDir: string } & EmitTsOptions;
  vb?: { outDir: string } & EmitVbOptions & {
    /**
     * VB ランタイム（JsonRpc / Dispatcher / IBridgeEmitter）の書き出し先。
     * 設定すると NuGet の WebView2Bridge.Runtime は不要（Contract プロジェクトには Newtonsoft.Json の参照だけが要る）。
     * 省略時は書き出さない（同リポジトリで ProjectReference する場合や NuGet を使う場合）
     */
    runtime?: { outDir: string };
    /**
     * WinForms 用 WebViewBridge の書き出し先（Host プロジェクト内）。
     * 設定すると NuGet の WebView2Bridge.WinForms は不要（Host には Microsoft.Web.WebView2 の参照が要る）
     */
    winforms?: { outDir: string };
  };
}

export interface GenerateResult {
  schema: ContractSchema;
  /** 書き込んだ（または --check で比較した）ファイルの絶対パス */
  files: string[];
  /** --check 時: 内容が一致しなかったファイル */
  stale: string[];
}

const AUTO_GENERATED_MARK = "<auto-generated>";

/** 契約を読み込み、schema → TS → VB を生成して書き出す */
export async function generate(config: GenerateConfig, opts: { cwd: string; check?: boolean }): Promise<GenerateResult> {
  const abs = (p: string): string => path.resolve(opts.cwd, p);
  const contract = await loadContract(abs(config.contract), config.contractExport ?? "contract");
  const schema = toSchema(contract);

  const outputs: { dir: string; ext: string; files: EmittedFile[] }[] = [];
  outputs.push({
    dir: path.dirname(abs(config.schemaOut)),
    ext: ".json",
    files: [{ path: path.basename(config.schemaOut), content: JSON.stringify(schema, null, 2) + "\n" }],
  });
  if (config.ts) {
    const { outDir, ...tsOpts } = config.ts;
    outputs.push({ dir: abs(outDir), ext: ".ts", files: emitTs(schema, tsOpts) });
  }
  if (config.vb) {
    const { outDir, runtime, winforms, ...vbOpts } = config.vb;
    outputs.push({ dir: abs(outDir), ext: ".vb", files: emitVb(schema, vbOpts) });
    if (runtime) outputs.push({ dir: abs(runtime.outDir), ext: ".vb", files: await emitVbRuntime("runtime") });
    if (winforms) outputs.push({ dir: abs(winforms.outDir), ext: ".vb", files: await emitVbRuntime("winforms") });
  }

  // 同じディレクトリに複数の出力（例: Generated/ にランタイムも置く）があっても、互いのファイルを消さないよう
  // ディレクトリ単位で「今回出力するファイル」をまとめてから古い生成物を消す
  const keepByDir = new Map<string, { ext: string; keep: Set<string> }>();
  for (const o of outputs) {
    const entry = keepByDir.get(o.dir) ?? { ext: o.ext, keep: new Set<string>() };
    for (const f of o.files) entry.keep.add(f.path);
    keepByDir.set(o.dir, entry);
  }

  const files: string[] = [];
  const stale: string[] = [];
  if (!opts.check) {
    for (const [dir, entry] of keepByDir) {
      await mkdir(dir, { recursive: true });
      await removeStaleGenerated(dir, entry.ext, entry.keep);
    }
  }
  for (const o of outputs) {
    for (const f of o.files) {
      const target = path.join(o.dir, f.path);
      files.push(target);
      if (opts.check) {
        const current = await readFile(target, "utf8").catch(() => null);
        // Windows の Git（core.autocrlf=true）が CRLF に変えていても「最新」と判定する。比較は改行を正規化して行う
        if (current === null || normalizeEol(current) !== normalizeEol(f.content)) stale.push(target);
      } else {
        await writeFile(target, f.content, "utf8");
      }
    }
  }
  return { schema, files, stale };
}

/**
 * 契約モジュール（.ts）を読み込む。
 * 公開パッケージは JS として実行されるので、TypeScript の契約は tsx の API で変換しながら import する
 * （利用側のアプリに tsx を要求しない。tsx はこのパッケージの dependency）。
 */
function normalizeEol(text: string): string {
  return text.replace(/\r\n/g, "\n");
}

async function loadContract(file: string, exportName: string): Promise<ContractDef> {
  const mod = (await tsImport(pathToFileURL(file).href, import.meta.url)) as Record<string, unknown>;
  const c = mod[exportName];
  if (!isContractDef(c)) {
    throw new GenerateError(`${file} does not export "${exportName}" created by defineContract()`);
  }
  return c;
}

function isContractDef(v: unknown): v is ContractDef {
  return (
    typeof v === "object" &&
    v !== null &&
    typeof (v as ContractDef).methods === "object" &&
    typeof (v as ContractDef).events === "object"
  );
}

/** 以前の生成物（auto-generated ヘッダ付き）のうち、今回出力しないものを消す */
async function removeStaleGenerated(dir: string, ext: string, keep: Set<string>): Promise<void> {
  const entries = await readdir(dir, { withFileTypes: true });
  for (const e of entries) {
    if (!e.isFile() || !e.name.endsWith(ext) || keep.has(e.name)) continue;
    const full = path.join(dir, e.name);
    const head = (await readFile(full, "utf8")).slice(0, 400);
    if (head.includes(AUTO_GENERATED_MARK)) await rm(full);
  }
}

