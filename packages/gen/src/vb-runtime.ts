/**
 * VB ランタイム（JsonRpc / Dispatcher / IBridgeEmitter / WebViewBridge）を生成物として書き出す。
 *
 * NuGet（WebView2Bridge.Runtime / WebView2Bridge.WinForms）を使わず、npm の gen だけで
 * アプリを成立させるための機能。ソースはパッケージ同梱の vb-runtime/（dotnet/ のコピー）。
 * 名前空間は NuGet 版と同じ（WebView2Bridge.Runtime / WebView2Bridge.WinForms）なので、
 * 契約から生成されるコードと呼び出し側は、どちらを使っても変わらない。
 *
 * Node 固有（fs）なので index.ts からは export しない（generate と同じ entry）。
 */
import { readFile } from "node:fs/promises";
import { createRequire } from "node:module";
import type { EmittedFile } from "./emitted.js";

export type VbRuntimeKind = "runtime" | "winforms";

/** 同梱している VB ランタイムのファイル名 */
export const VB_RUNTIME_FILES: Record<VbRuntimeKind, readonly string[]> = {
  runtime: ["JsonRpc.vb", "Dispatcher.vb", "IBridgeEmitter.vb"],
  winforms: ["WebViewBridge.vb"],
};

const VB_RUNTIME_DESCRIPTION: Record<VbRuntimeKind, string> = {
  runtime: "JSON-RPC runtime (namespace WebView2Bridge.Runtime; needs Newtonsoft.Json)",
  winforms: "WinForms bridge (namespace WebView2Bridge.WinForms; needs Microsoft.Web.WebView2 and the runtime)",
};

/** この gen パッケージのバージョン（生成ヘッダに埋める。src/ からも dist/ からも ../package.json） */
export function genPackageVersion(): string {
  const require = createRequire(import.meta.url);
  const pkg = require("../package.json") as { version: string };
  return pkg.version;
}

export function vbRuntimeHeader(kind: VbRuntimeKind, version: string): string {
  return [
    "' <auto-generated>",
    `'     webview2-bridge VB ${VB_RUNTIME_DESCRIPTION[kind]}`,
    `'     copied by @ishibashi0112/webview2-bridge-gen ${version} from its bundled vb-runtime/${kind}/.`,
    "'     DO NOT EDIT. Changes will be lost when `pnpm gen` runs.",
    "'     To update, upgrade the npm package and run the generator again.",
    "' </auto-generated>",
    "",
  ].join("\n");
}

/** 同梱ランタイムを読み、auto-generated ヘッダを付けて EmittedFile にする */
export async function emitVbRuntime(kind: VbRuntimeKind, options: { version?: string } = {}): Promise<EmittedFile[]> {
  const version = options.version ?? genPackageVersion();
  const base = new URL(`../vb-runtime/${kind}/`, import.meta.url);
  const out: EmittedFile[] = [];
  for (const name of VB_RUNTIME_FILES[kind]) {
    const body = await readFile(new URL(name, base), "utf8");
    out.push({ path: name, content: vbRuntimeHeader(kind, version) + body.replace(/\r\n/g, "\n") });
  }
  return out;
}
