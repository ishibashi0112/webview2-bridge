import { describe, expect, it } from "vitest";
import { emitVb, vbTypeName } from "../src/emit-vb.js";
import { buildContractModel } from "../src/model.js";
import { contractToJsonSchema } from "../src/to-schema.js";
import { kitchenSinkContract } from "./fixtures/kitchen-sink-contract.js";
import { sampleContract } from "./fixtures/sample-contract.js";

const VB_FILES = ["Dto.vb", "Interfaces.vb", "Dispatcher.Generated.vb", "Events.vb"];

describe("emitVb", () => {
  it("sample contract (snapshot)", async () => {
    const files = emitVb(buildContractModel(contractToJsonSchema(sampleContract)));
    expect(Object.keys(files)).toEqual(VB_FILES);
    for (const name of VB_FILES) {
      await expect(files[name]).toMatchFileSnapshot(`__snapshots__/sample/${name}`);
    }
  });

  it("kitchen-sink contract (snapshot)", async () => {
    const files = emitVb(buildContractModel(contractToJsonSchema(kitchenSinkContract)));
    for (const name of VB_FILES) {
      await expect(files[name]).toMatchFileSnapshot(`__snapshots__/kitchen-sink/${name}`);
    }
  });

  it("every generated file starts with the auto-generated marker and Option Strict On", () => {
    const files = emitVb(buildContractModel(contractToJsonSchema(kitchenSinkContract)));
    for (const content of Object.values(files)) {
      expect(content.startsWith("' <auto-generated />")).toBe(true);
      expect(content).toContain("Option Strict On");
    }
  });
});

describe("vbTypeName", () => {
  it("wraps value types in Nullable(Of T) when optional or nullable", () => {
    expect(vbTypeName({ kind: "integer", nullable: false }, true)).toBe("Integer");
    expect(vbTypeName({ kind: "integer", nullable: false }, false)).toBe("Nullable(Of Integer)");
    expect(vbTypeName({ kind: "boolean", nullable: true }, true)).toBe("Nullable(Of Boolean)");
    expect(vbTypeName({ kind: "long", nullable: false }, true)).toBe("Long");
    expect(vbTypeName({ kind: "number", nullable: false }, true)).toBe("Double");
  });

  it("keeps reference types as-is", () => {
    expect(vbTypeName({ kind: "string", nullable: true }, false)).toBe("String");
    expect(vbTypeName({ kind: "enum", className: "X", nullable: false }, false)).toBe("String");
    expect(vbTypeName({ kind: "object", className: "Part", nullable: false }, false)).toBe("Part");
    expect(vbTypeName({ kind: "array", items: { kind: "integer", nullable: true }, nullable: false })).toBe(
      "List(Of Nullable(Of Integer))",
    );
  });
});
