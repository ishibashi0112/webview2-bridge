import { mkdtemp, readdir, readFile, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { generate, type GenerateConfig } from "../src/generate.js";

let dir: string;
beforeEach(async () => {
  dir = await mkdtemp(path.join(os.tmpdir(), "wv2b-gen-"));
  // defineContract は identity 関数なので、テスト用の契約は zod だけで書く
  // （vitest のワーカー内では tsImport 越しに src/index.ts を辿れないため。実際の CLI 経由の読み込みは
  //   別プロジェクトからの検証で確認している）
  await writeFile(
    path.join(dir, "contract.ts"),
    `import { z } from "zod";
export const contract = {
  methods: { orders: { list: { input: z.object({ id: z.string() }), output: z.object({ ok: z.boolean() }) } } },
  events: { tick: z.object({ at: z.string() }) },
};
`,
  );
});
afterEach(async () => {
  await rm(dir, { recursive: true, force: true });
});

function config(): GenerateConfig {
  return {
    contract: "contract.ts",
    schemaOut: "contract.schema.json",
    ts: { outDir: "web/generated", contractImport: "../../contract" },
    vb: {
      outDir: "dotnet/App.Contract/Generated",
      namespace: "App.Contract",
      runtime: { outDir: "dotnet/App.Contract/Generated" }, // 契約の生成物と同じディレクトリに置いても消し合わない
      winforms: { outDir: "dotnet/App.Host/Bridge" },
    },
  };
}

describe("generate (with VB runtime output)", () => {
  it("writes contract outputs, runtime and winforms files; --check passes afterwards", async () => {
    const r = await generate(config(), { cwd: dir });
    const rel = r.files.map((f) => path.relative(dir, f).replace(/\\/g, "/")).sort();
    expect(rel).toEqual(
      [
        "contract.schema.json",
        "web/generated/contract-types.ts",
        "dotnet/App.Contract/Generated/Dto.vb",
        "dotnet/App.Contract/Generated/Interfaces.vb",
        "dotnet/App.Contract/Generated/Dispatcher.Generated.vb",
        "dotnet/App.Contract/Generated/Events.vb",
        "dotnet/App.Contract/Generated/JsonRpc.vb",
        "dotnet/App.Contract/Generated/Dispatcher.vb",
        "dotnet/App.Contract/Generated/IBridgeEmitter.vb",
        "dotnet/App.Host/Bridge/WebViewBridge.vb",
      ].sort(),
    );
    const generated = await readdir(path.join(dir, "dotnet/App.Contract/Generated"));
    expect(generated.sort()).toEqual(
      ["Dispatcher.Generated.vb", "Dispatcher.vb", "Dto.vb", "Events.vb", "IBridgeEmitter.vb", "Interfaces.vb", "JsonRpc.vb"].sort(),
    );
    expect(await readFile(path.join(dir, "dotnet/App.Contract/Generated/Dispatcher.vb"), "utf8")).toContain("' <auto-generated>");

    const check = await generate(config(), { cwd: dir, check: true });
    expect(check.stale).toEqual([]);
  });

  it("removes stale auto-generated files but keeps hand-written ones", async () => {
    await generate(config(), { cwd: dir });
    const gen = path.join(dir, "dotnet/App.Contract/Generated");
    await writeFile(path.join(gen, "Old.vb"), "' <auto-generated>\n' old\n' </auto-generated>\nClass Old\nEnd Class\n");
    await writeFile(path.join(gen, "Mine.vb"), "Class Mine\nEnd Class\n");
    await generate(config(), { cwd: dir });
    const names = await readdir(gen);
    expect(names).not.toContain("Old.vb");
    expect(names).toContain("Mine.vb");
  });

  it("--check reports missing runtime files", async () => {
    await generate(config(), { cwd: dir });
    await rm(path.join(dir, "dotnet/App.Host/Bridge/WebViewBridge.vb"));
    const check = await generate(config(), { cwd: dir, check: true });
    expect(check.stale.map((f) => path.basename(f))).toEqual(["WebViewBridge.vb"]);
  });
});
