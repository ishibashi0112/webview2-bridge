import { readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { emitVbRuntime, genPackageVersion, VB_RUNTIME_FILES } from "../src/vb-runtime.js";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const SOURCE_DIRS = { runtime: "dotnet/WebView2Bridge.Runtime", winforms: "dotnet/WebView2Bridge.WinForms" } as const;

describe("emitVbRuntime", () => {
  it("bundled vb-runtime/ is in sync with dotnet/ (run `pnpm sync:vb-runtime` if this fails)", async () => {
    for (const [kind, dir] of Object.entries(SOURCE_DIRS) as [keyof typeof SOURCE_DIRS, string][]) {
      const files = await emitVbRuntime(kind, { version: "x" });
      expect(files.map((f) => f.path)).toEqual([...VB_RUNTIME_FILES[kind]]);
      for (const f of files) {
        const source = (await readFile(path.join(repoRoot, dir, f.path), "utf8")).replace(/\r\n/g, "\n");
        const body = f.content.slice(f.content.indexOf("' </auto-generated>\n") + "' </auto-generated>\n".length);
        expect(body, `${kind}/${f.path}`).toBe(source);
      }
    }
  });

  it("prefixes an auto-generated header with the package version", async () => {
    const [f] = await emitVbRuntime("runtime", { version: "9.9.9" });
    expect(f!.content.startsWith("' <auto-generated>\n")).toBe(true);
    expect(f!.content).toContain("@ishibashi0112/webview2-bridge-gen 9.9.9");
    expect(f!.content).toContain("' </auto-generated>\nOption Strict On");
    expect(genPackageVersion()).toMatch(/^\d+\.\d+\.\d+/);
  });

  it("keeps the same namespaces as the NuGet packages", async () => {
    const runtime = await emitVbRuntime("runtime");
    for (const f of runtime) expect(f.content).toContain("Namespace Global.WebView2Bridge.Runtime");
    const [bridge] = await emitVbRuntime("winforms");
    expect(bridge!.content).toContain("Namespace Global.WebView2Bridge.WinForms");
    expect(bridge!.content).toContain("Imports WebView2Bridge.Runtime");
  });
});
